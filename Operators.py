# Python Operators

a = 20
b = 10

# Arithmetic Operators
print("Arithmetic Operators")
print("Addition       :", a + b)
print("Subtraction    :", a - b)
print("Multiplication :", a * b)
print("Division       :", a / b)
print("Modulus        :", a % b)

# Comparison Operators
print("\nComparison Operators")
print("a == b :", a == b)
print("a != b :", a != b)
print("a > b  :", a > b)
print("a < b  :", a < b)

# Assignment Operator
print("\nAssignment Operator")
c = a
print("c =", c)

# Logical Operators
print("\nLogical Operators")
print("a > 10 and b > 5 :", a > 10 and b > 5)
print("a > 25 or b > 5  :", a > 25 or b > 5)
print("not(a > b)       :", not(a > b))
