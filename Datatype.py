# Python Data Types

name = "Ajay"          # String
age = 20               # Integer
height = 5.8           # Float
student = True         # Boolean

print("Name:", name)
print("Name:", type(name))

print("Age:", age)
print("Age:", type(age))

print("Height:", height)
print("Height:", type(height))

print("Student:", student)
print("Student:", type(student))
